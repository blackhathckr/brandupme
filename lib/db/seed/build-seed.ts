/* ── First admin ────────────────────────────────────────────────────────── */

/**
 * Password hashing must match lib/auth/password.ts exactly, so a seeded
 * account can log in through the normal path. Format: pbkdf2$<iters>$<salt>$<hash>
 */
const ITERATIONS = 210_000;
function hashPassword(plain: string): string {
  const salt = randomBytes(16);
  const dk = pbkdf2Sync(plain, salt, ITERATIONS, 32, "sha256");
  // Buffer.from(...) is explicit because the Workers type definitions
  // shadow Node's Buffer, so the encoding overload of toString is not seen.
  return `pbkdf2$${ITERATIONS}$${Buffer.from(salt).toString("base64")}$${Buffer.from(dk).toString("base64")}`;
}

const adminEmail = process.env.SEED_ADMIN_EMAIL ?? "admin@brandupme.ae";

/**
 * Generated unless supplied. The resulting seed.sql carries this account's
 * password hash, which is why that file is gitignored - the repository is
 * public. Set SEED_ADMIN_PASSWORD to choose your own before running.
 */
const adminPassword =
  process.env.SEED_ADMIN_PASSWORD ?? Buffer.from(randomBytes(9)).toString("base64url");

out.push("-- First admin account");
out.push(
  `INSERT OR IGNORE INTO users (email, name, kind, status, password_hash, created_at, updated_at)
   VALUES (${q(adminEmail)}, 'BrandUpMe Admin', 'staff', 'active', ${q(hashPassword(adminPassword))}, ${now}, ${now});`,
);
out.push(
  `INSERT OR IGNORE INTO user_roles (user_id, role_id) VALUES (
    (SELECT id FROM users WHERE email = ${q(adminEmail)}),
    (SELECT id FROM roles WHERE slug = 'super-admin'));`,
);
out.push("");

mkdirSync("db", { recursive: true });
